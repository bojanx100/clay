// Provider construction and first-message dispatch for a prepared query.

var pushControlInput = require("./coop-coordinator-context-delivery").pushControlInput;
var executionFence = require("./coop-control-fence");
var failQueryStart = require("./sdk-bridge-query-start-failure").failQueryStart;

function failedResult(ctx, session, error, handle, fence, submission) {
  failQueryStart({ session: session, error: error, handle: handle, controlledFence: fence,
    onProcessingChanged: ctx.onProcessingChanged, sendAndRecord: ctx.sendAndRecord, sm: ctx.sm });
  return { ok: false, reason: "provider_start_failed", submission: submission || "not_submitted" };
}

function persistInitialTitle(ctx, session, title) {
  if (!title) return;
  if (!session.title) {
    session.title = title;
    session.titleAutoGenerated = true;
    ctx.sm.saveSessionFile(session);
    ctx.sm.broadcastSessionList();
  } else if (session.title === title) {
    session.titleAutoGenerated = true;
    ctx.sm.saveSessionFile(session);
  }
}

async function createHandle(ctx, session, adapter, options, title, fence) {
  var handle;
  console.log("[sdk-bridge] calling adapter.createQuery... vendor=" + adapter.vendor);
  try {
    executionFence.assertAction(session, "provider_start", fence);
    handle = await adapter.createQuery(options);
    Object.defineProperty(handle, "_clayReadOnlyExecution", {
      value: options.readOnlyExecution === true, configurable: true });
    executionFence.assertAction(session, "provider_start", fence);
    if (fence) fence.markProviderStarted();
    console.log("[sdk-bridge] createQuery returned handle, vendor=" + adapter.vendor);
    persistInitialTitle(ctx, session, title);
    return { handle: handle };
  } catch (error) {
    return { result: failedResult(ctx, session, error, handle, fence) };
  }
}

function adoptHandle(session, handle, linuxUser) {
  if (handle._adapterState) {
    session._adapterWorkerState = handle._adapterState;
    if (handle._adapterState.worker) session.worker = handle._adapterState.worker;
  }
  if (linuxUser) {
    session.abortController = { abort: function () { handle.abort(); },
      signal: { aborted: false, addEventListener: function () {} } };
  }
  session.queryInstance = handle;
}

function pushInitial(ctx, session, handle, text, images, fence, controlInput) {
  console.log("[sdk-bridge] pushing initial message via handle.pushMessage...");
  try {
    var accepted = controlInput !== undefined ? pushControlInput(ctx, session, handle, controlInput, images) :
      handle.pushMessage(text, images);
    if (accepted === false) {
      return { failed: true, result: failedResult(ctx, session, new Error("Provider rejected input"), handle, fence) };
    }
    executionFence.assertAction(session, "provider_start", fence);
  } catch (error) {
    var current = executionFence.isIncarnationCurrent(session, fence);
    var result = failedResult(ctx, session, error, handle, fence, "uncertain");
    if (current && !session.queryInstance) session.queryInstance = null;
    return { failed: true, result: result };
  }
  console.log("[sdk-bridge] pushMessage done, starting processQueryStream...");
  return { failed: false };
}

function finishInput(ctx, session, handle, fence) {
  if (!session.singleTurn) return { failed: false };
  try {
    // Request/response providers have no streaming input queue to finalize.
    // Handles that expose one still receive the explicit single-turn close.
    if (typeof handle.endInput === "function") handle.endInput();
    executionFence.assertAction(session, "provider_start", fence);
    return { failed: false };
  } catch (error) {
    return { failed: true, result: failedResult(ctx, session, error, handle, fence, "uncertain") };
  }
}

function flushPendingPushes(ctx, session, handle, fence) {
  if (!session.pendingPush || session.pendingPush.length === 0) return { failed: false };
  var backlog = session.pendingPush;
  session.pendingPush = [];
  console.log("[sdk-bridge] flushing " + backlog.length + " buffered message(s) into new query");
  try {
    for (var i = 0; i < backlog.length; i++) {
      var accepted = pushControlInput(ctx, session, handle, backlog[i].text, backlog[i].images);
      if (accepted === false) throw new Error("Provider rejected buffered input");
    }
    executionFence.assertAction(session, "provider_start", fence);
    return { failed: false };
  } catch (error) {
    return { failed: true, result: failedResult(ctx, session, error, handle, fence, "uncertain") };
  }
}

async function launchQuery(ctx, session, adapter, prepared, text, images, linuxUser, fence) {
  var created = await createHandle(ctx, session, adapter, prepared.options,
    prepared.initialTitle, fence);
  if (Object.prototype.hasOwnProperty.call(created, "result")) return created.result;
  try {
    executionFence.assertAction(session, "provider_start", fence);
  } catch (error) {
    return failedResult(ctx, session, error, created.handle, fence);
  }
  var pushed = pushInitial(ctx, session, created.handle, text, images, fence, prepared.controlInput);
  if (pushed.failed) return pushed.result;
  adoptHandle(session, created.handle, linuxUser);
  var flushed = flushPendingPushes(ctx, session, created.handle, fence);
  if (flushed.failed) return flushed.result;
  var finished = finishInput(ctx, session, created.handle, fence);
  if (finished.failed) return finished.result;
  session.lastActivityAt = Date.now();
  session.streamPromise = ctx.processQueryStream(session, fence).catch(function () {});
  return { ok: true, submission: "submitted" };
}

module.exports = { launchQuery: launchQuery };
