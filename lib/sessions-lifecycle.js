var crypto = require("crypto");
var {
  orchestrationStateForClient,
  orchestrationTasksForClient,
} = require("./orchestration-task-state");
var coopChannels = require("./project-coop-channels");
var normalizeControlledBy = require("./coop-control-provenance").normalizeControlledBy;
var historyStore = require("./sessions-history-store");

function attachSessionLifecycle(ctx) {
  var sessions = ctx.sessions;
  var allocateLocalId = ctx.allocateLocalId;
  var saveSessionFile = ctx.saveSessionFile;
  var send = ctx.send;
  var sendTo = ctx.sendTo;
  var sendEach = ctx.sendEach;
  var getActiveSessionId = ctx.getActiveSessionId;
  var setActiveSessionId = ctx.setActiveSessionId;
  var getSingleUserUnread = ctx.getSingleUserUnread;
  var getCapabilitiesByVendor = ctx.getCapabilitiesByVendor;
  var getDefaultVendor = ctx.getDefaultVendor;
  var getSlashCommands = ctx.getSlashCommands;
  var getSlashCommandsForVendor = ctx.getSlashCommandsForVendor;
  var getEffectiveAutomationMode = ctx.getEffectiveAutomationMode;
  var queuedUserMessagesForClient = ctx.queuedUserMessagesForClient;
  var broadcastSessionList = ctx.broadcastSessionList;
  var replayHistory = ctx.replayHistory;

  function sessionHistoryLength(session) {
    if (historyStore.isLazy(session) && !historyStore.isResident(session) &&
        Number.isInteger(session._persistedHistoryLength)) {
      return session._persistedHistoryLength;
    }
    return Array.isArray(session.history) ? session.history.length : 0;
  }

  function buildNewSession(sessionOpts, lastViewedAt) {
    var localId = allocateLocalId();
    return {
      localId: localId,
      queryInstance: null,
      messageQueue: null,
      cliSessionId: (sessionOpts && sessionOpts.cliSessionId) || null,
      // Allocate Clay's durable session identity before the first provider
      // turn. User messages are appended before the provider assigns its
      // cliSessionId, so leaving this null makes every fresh GUI session fail
      // persistence with "The message could not be saved".
      storageId: (sessionOpts && sessionOpts.storageId) || (sessionOpts && sessionOpts.cliSessionId) || crypto.randomUUID(),
      blocks: {},
      sentToolResults: {},
      pendingPermissions: {},
      pendingAskUser: {},
      allowedTools: {},
      isProcessing: false,
      title: "",
      titleAutoGenerated: false,
      turnCount: 0,
      createdAt: Date.now(),
      lastActivity: Date.now(),
      lastViewedAt: lastViewedAt,
      history: [],
      messageUUIDs: [],
      ownerId: (sessionOpts && sessionOpts.ownerId) || null,
      sessionVisibility: (sessionOpts && sessionOpts.sessionVisibility) || "shared",
      bookmarked: false,
      favoriteOrder: null,
      vendor: (sessionOpts && sessionOpts.vendor) || null,
      providerRouteId: (sessionOpts && sessionOpts.providerRouteId) || null,
      model: (sessionOpts && sessionOpts.model) || null,
      effort: (sessionOpts && sessionOpts.effort) || null,
      automationMode: (sessionOpts && sessionOpts.automationMode) || null,
      permissionMode: (sessionOpts && sessionOpts.permissionMode) || null,
      codexApproval: (sessionOpts && sessionOpts.codexApproval) || null,
      codexSandbox: (sessionOpts && sessionOpts.codexSandbox) || null,
      codexWebSearch: (sessionOpts && sessionOpts.codexWebSearch) || null,
      coordinationMode: !!(sessionOpts && sessionOpts.coordinationMode),
      coopHome: !!(sessionOpts && sessionOpts.coopHome),
      coopChannel: coopChannels.normalizeChannelMetadata(
        sessionOpts && sessionOpts.coopChannel),
      coopControlledBy: normalizeControlledBy(sessionOpts && sessionOpts.coopControlledBy),
      mode: (sessionOpts && sessionOpts.mode === "tui") ? "tui" : "gui",
      terminalId: null,
    };
  }

  function createSession(sessionOpts, targetWs) {
    var session = buildNewSession(sessionOpts, Date.now());
    sessions.set(session.localId, session);
    switchSession(session.localId, targetWs);
    return session;
  }

  function createSessionRaw(sessionOpts) {
    var session = buildNewSession(sessionOpts, null);
    session.dangerouslySkipPermissions = !!(sessionOpts && sessionOpts.dangerouslySkipPermissions);
    sessions.set(session.localId, session);
    return session;
  }

  function switchSession(localId, targetWs, transform, replayOptions) {
    var session = sessions.get(localId);
    if (!session) return;
    var replaySource = replayOptions && replayOptions.replaySession
      ? replayOptions.replaySession
      : session;

    setActiveSessionId(localId);
    session.lastViewedAt = Date.now();
    if (!session._lastViewedPersistedAt || (session.lastViewedAt - session._lastViewedPersistedAt) > 15000) {
      session._lastViewedPersistedAt = session.lastViewedAt;
      setImmediate(function () { saveSessionFile(session, { viewOnly: true }); });
    }
    if (targetWs) {
      targetWs._clayActiveSession = localId;
      if (targetWs._clayUnread) targetWs._clayUnread[localId] = 0;
    } else if (sendEach) {
      sendEach(function (ws) {
        ws._clayActiveSession = localId;
        ws._clayDeliveredLen = sessionHistoryLength(session);
      });
    }
    getSingleUserUnread()[localId] = 0;

    var _send = (targetWs && sendTo) ? function (obj) { sendTo(targetWs, obj); } : send;
    var _capsByVendor = getCapabilitiesByVendor() || {};
    var _sessionVendor = session.vendor || getDefaultVendor() || "claude";
    var _vendorCaps = _capsByVendor[_sessionVendor] || {};
    _send({ type: "session_switched", id: localId, title: session.title || null, cliSessionId: session.cliSessionId || null, loop: session.loop || null, vendor: session.vendor || null, providerRouteId: session.providerRouteId || null, requestedModel: session.requestedModel || session.model || null, verifiedModel: session.verifiedModel || null, modelVerificationSource: session.modelVerificationSource || null, automationMode: getEffectiveAutomationMode(session), permissionMode: session.permissionMode || null, codexApproval: session.codexApproval || null, codexSandbox: session.codexSandbox || null, codexWebSearch: session.codexWebSearch || null, hasHistory: sessionHistoryLength(session) > 0, capabilities: _vendorCaps, isProcessing: !!session.isProcessing, mode: session.mode || "gui", terminalId: typeof session.terminalId === "number" ? session.terminalId : null, runtimeMode: session.runtimeMode || null, runtimeTerminalId: typeof session.runtimeTerminalId === "number" ? session.runtimeTerminalId : null, tuiSuspended: !!session.tuiSuspended, queueingDisabled: !!session.queueingDisabled, queuedUserMessages: queuedUserMessagesForClient(session), orchestrationTasks: orchestrationTasksForClient(session), orchestrationState: orchestrationStateForClient(session), coordinationMode: !!session.coordinationMode, coopHome: !!session.coopHome, coopChannel: coopChannels.channelForClient(session.coopChannel), demotionPending: !!session.demoteCoordinatorWhenIdle, orchestrationParent: session.orchestrationParent || null });
    var _vendorCmds = getSlashCommandsForVendor(_sessionVendor) || getSlashCommands() || [];
    _send({ type: "slash_commands", commands: _vendorCmds, vendor: _sessionVendor });
    broadcastSessionList();
    replayHistory(replaySource, undefined, targetWs, transform, replayOptions);
    historyStore.release(replaySource);
    if (replaySource !== session) historyStore.release(session);

    if (session.isProcessing) {
      _send({ type: "status", status: "processing" });
    }

    var pendingIds = Object.keys(session.pendingPermissions);
    for (var i = 0; i < pendingIds.length; i++) {
      var p = session.pendingPermissions[pendingIds[i]];
      _send({
        type: "permission_request_pending",
        requestId: p.requestId,
        toolName: p.toolName,
        toolInput: p.toolInput,
        toolUseId: p.toolUseId,
        decisionReason: p.decisionReason,
      });
    }

    if (session._mentionInProgress && session._mentionActiveMateId) {
      _send({ type: "mention_processing", mateId: session._mentionActiveMateId, active: true });
    }
  }

  function resumeSession(cliSessionId, opts, targetWs) {
    var existing = null;
    sessions.forEach(function (s) {
      if (s.cliSessionId === cliSessionId) existing = s;
    });
    if (existing) {
      existing.lastActivity = Date.now();
      existing.lastViewedAt = Date.now();
      switchSession(existing.localId, targetWs);
      return existing;
    }

    var cliHistory = (opts && opts.history) || [];
    var title = (opts && opts.title) || "Resumed session";
    var localId = allocateLocalId();
    var session = {
      localId: localId,
      queryInstance: null,
      messageQueue: null,
      cliSessionId: cliSessionId,
      blocks: {},
      sentToolResults: {},
      pendingPermissions: {},
      pendingAskUser: {},
      allowedTools: {},
      isProcessing: false,
      title: title,
      createdAt: Date.now(),
      lastActivity: Date.now(),
      lastViewedAt: Date.now(),
      history: cliHistory,
      messageUUIDs: [],
      bookmarked: false,
      favoriteOrder: null,
    };
    if (opts && opts.vendor) session.vendor = opts.vendor;
    if (opts && opts.ownerId) session.ownerId = opts.ownerId;
    sessions.set(localId, session);
    saveSessionFile(session);
    switchSession(localId, targetWs);
    return session;
  }

  return {
    createSession: createSession,
    createSessionRaw: createSessionRaw,
    switchSession: switchSession,
    resumeSession: resumeSession,
  };
}

module.exports = {
  attachSessionLifecycle: attachSessionLifecycle,
};
