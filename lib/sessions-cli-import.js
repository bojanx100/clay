var fs = require("fs");
var config = require("./config");
var tombstones = require("./tombstones");
var copilotSessions = require("./copilot-sessions");
var coopProvenance = require("./coop-control-provenance");

var historyStore = require("./sessions-history-store");

function attachSessionCliImport(ctx) {
  var cwd = ctx.cwd;
  var sessions = ctx.sessions;
  var allocateLocalId = ctx.allocateLocalId;
  var saveSessionFile = ctx.saveSessionFile;
  var broadcastSessionList = ctx.broadcastSessionList;
  var isValidCliSessionId = ctx.isValidCliSessionId;
  var cliSessionsDir = ctx.cliSessionsDir;
  var readCliSessionDescriptor = ctx.readCliSessionDescriptor;
  var readCodexThreadNames = ctx.readCodexThreadNames;
  var listCodexRolloutFiles = ctx.listCodexRolloutFiles;
  var readCodexSessionDescriptor = ctx.readCodexSessionDescriptor;
  var findCodexRolloutByThreadId = ctx.findCodexRolloutByThreadId;
  var getSessionStorageId = ctx.getSessionStorageId || function (session) {
    return session && (session.storageId || session.cliSessionId) || null;
  };

  function addSessionCurrentIds(set, session) {
    if (!set || !session) return;
    if (session.cliSessionId) set.add(session.cliSessionId);
    if (session.storageId) set.add(session.storageId);
  }

  function addSessionHistoricalProviderIds(set, session) {
    if (!set || !session) return;
    // Derived once at load time, so this scan -- which runs over every session at
    // boot -- cannot page every transcript back into memory.
    if (Array.isArray(session._historicalProviderIds)) {
      for (var c = 0; c < session._historicalProviderIds.length; c++) {
        set.add(session._historicalProviderIds[c]);
      }
      // The cache is a snapshot of load time, and is only authoritative while the
      // transcript is still released -- nothing can have been appended to it since.
      // Once it is resident the session may have recorded new provider ids, so
      // fall through and scan rather than trust a stale snapshot.
      if (historyStore.isLazy(session) && !historyStore.isResident(session)) return;
    }
    if (!Array.isArray(session.history)) return;
    for (var i = 0; i < session.history.length; i++) {
      var item = session.history[i];
      if (!item || typeof item !== "object") continue;
      if (item.type === "session_id" && item.cliSessionId) {
        set.add(item.cliSessionId);
      }
      if (item.type === "result" && item.sessionId) {
        set.add(item.sessionId);
      }
    }
  }

  function materializeCliSession(desc, options) {
    options = options || {};
    var localId = allocateLocalId();
    var vendor = desc.vendor || "claude";
    var session = {
      localId: localId,
      queryInstance: null,
      messageQueue: null,
      cliSessionId: desc.cliSid,
      blocks: {},
      sentToolResults: {},
      pendingPermissions: {},
      pendingAskUser: {},
      isProcessing: false,
      title: desc.title,
      titleManuallySet: !!desc.title,
      titleAutoGenerated: false,
      createdAt: desc.createdAt,
      lastActivity: desc.lastActivity,
      history: [],
      messageUUIDs: [],
      lastRewindUuid: null,
      vendor: vendor,
      providerRouteId: desc.providerRouteId || null,
      model: desc.model || null,
      requestedModel: desc.model || null,
      mode: vendor === "claude" ? "tui" : "gui",
      terminalId: null,
      runtimeMode: null,
      runtimeTerminalId: null,
      sessionVisibility: "shared",
      bookmarked: false,
      favoriteOrder: null,
    };
    if (options.adopted) session.adopted = true;
    sessions.set(localId, session);
    try { saveSessionFile(session); } catch (e) {}
    return localId;
  }

  function isHandoffRolloutDescriptor(desc) {
    if (!desc) return false;
    var head = String(desc.preview || desc.title || "").slice(0, 400);
    if (head.indexOf("<clay_handoff_context>") !== -1) return true;
    if (head.indexOf("[Context from previous") !== -1) return true;
    return false;
  }

  function adoptOrphanedCliSessions() {
    var instance = config.loadConfig();
    if (instance && instance.nativeSessionDiscovery === false) return;
    var files;
    try { files = fs.readdirSync(cliSessionsDir()); } catch (e) { return; }

    var knownCliIds = new Set();
    var hiddenKnownIds = new Set();
    sessions.forEach(function (s) {
      addSessionCurrentIds(knownCliIds, s);
      addSessionHistoricalProviderIds(knownCliIds, s);
      if (s.hidden) {
        addSessionCurrentIds(hiddenKnownIds, s);
        addSessionHistoricalProviderIds(hiddenKnownIds, s);
      }
    });

    var adopted = 0;
    var resurrectAttempts = 0;
    for (var i = 0; i < files.length; i++) {
      if (!files[i].endsWith(".jsonl")) continue;
      var cliSid = files[i].slice(0, -".jsonl".length);
      if (knownCliIds.has(cliSid)) {
        if (hiddenKnownIds.has(cliSid)) resurrectAttempts++;
        continue;
      }
      if (tombstones.has(cliSid)) continue;

      var desc = readCliSessionDescriptor(cliSid);
      if (!desc) continue;
      if (isHandoffRolloutDescriptor(desc)) continue;
      materializeCliSession(desc, { adopted: true });
      knownCliIds.add(cliSid);
      adopted++;
      console.log("[sessions][unhide-watch] adopted orphan CLI rollout " + cliSid + " as VISIBLE: " + JSON.stringify((desc.title || "").slice(0, 50)));
    }

    if (adopted > 0 || resurrectAttempts > 0) {
      console.log("[sessions] Adopted " + adopted + " CLI session(s) for " + cwd + " (resurrect-guard hits: " + resurrectAttempts + ")");
    }
  }

  function shouldIncludeForImportVendor(item, vendorFilter) {
    if (!vendorFilter) return true;
    var vendor = item && item.vendor ? item.vendor : "claude";
    if (vendor === "github-copilot") return item.copilotFamily === vendorFilter;
    return vendor === vendorFilter;
  }

  function isHiddenCoopControlledSession(session) {
    return !!(session && session.hidden && coopProvenance.isCoopControlled(session));
  }

  // Coop's canonical conversation and its control-plane sessions are
  // infrastructure, not importable history: they are re-created and re-stamped
  // by the control plane itself, so they stay out of the picker even when the
  // caller explicitly asks for Coop-managed rows.
  function isCoopInfrastructureSession(session) {
    if (!session) return false;
    if (coopProvenance.isCanonicalCoopSession(session)) return true;
    return session.coordinationRole === "coop_control_plane";
  }

  // A closed Coop-owned session is not a worker. Auto-archived orchestration
  // work is why this exclusion exists at all (it would otherwise bury the
  // picker), but the owner closing a real Coop-owned conversation must be able
  // to get it back. So the exclusion holds by default and lifts when the caller
  // opts in -- except for infrastructure, which is never importable.
  function isImportExcludedCoopSession(session, includeCoopManaged) {
    if (!isHiddenCoopControlledSession(session)) return false;
    if (!includeCoopManaged) return true;
    return isCoopInfrastructureSession(session);
  }

  function findWorkerSessionForTask(task) {
    if (!task) return null;
    var worker = null;
    if (task.workerStorageId) {
      sessions.forEach(function (candidate) {
        if (!worker && getSessionStorageId(candidate) === task.workerStorageId) {
          worker = candidate;
        }
      });
    }
    if (worker || task.workerSessionId == null) return worker;
    var localId = Number(task.workerSessionId);
    return Number.isFinite(localId) ? sessions.get(localId) || null : null;
  }

  function restoreCoordinatorWorkers(session, restoredSessions) {
    if (!session || !session.coordinationMode ||
        !Array.isArray(session.orchestrationTasks)) return;
    for (var i = 0; i < session.orchestrationTasks.length; i++) {
      var worker = findWorkerSessionForTask(session.orchestrationTasks[i]);
      if (!worker || worker === session || restoredSessions.has(worker)) continue;
      restoredSessions.add(worker);
      if (worker.hidden) {
        worker.hidden = false;
        worker.closedAt = null;
        saveSessionFile(worker);
      }
      restoreCoordinatorWorkers(worker, restoredSessions);
    }
  }

  function listAdoptableCliSessions(vendorFilter, options) {
    vendorFilter = vendorFilter === "claude" || vendorFilter === "codex" ? vendorFilter : "";
    var includeCoopManaged = !!(options && options.includeCoopManaged);
    var knownCliIds = new Set();
    var workerCliIds = new Set();
    var coopManagedCliIds = new Set();
    var hiddenCliIds = new Set();
    var hiddenCliSessions = new Map();
    sessions.forEach(function (s) {
      if (s.orchestrationParent || isImportExcludedCoopSession(s, includeCoopManaged)) {
        addSessionCurrentIds(workerCliIds, s);
        addSessionHistoricalProviderIds(workerCliIds, s);
      } else if (isHiddenCoopControlledSession(s)) {
        // Admitted by the opt-in above. Flag it so the picker can label the row
        // as Coop-managed rather than presenting it as an ordinary close.
        addSessionCurrentIds(coopManagedCliIds, s);
      }
      if (s.hidden) {
        if (s.cliSessionId) {
          hiddenCliIds.add(s.cliSessionId);
          hiddenCliSessions.set(s.cliSessionId, s);
        }
      } else {
        addSessionCurrentIds(knownCliIds, s);
      }
      addSessionHistoricalProviderIds(knownCliIds, s);
    });

    var out = [];

    var claudeFiles;
    try { claudeFiles = fs.readdirSync(cliSessionsDir()); } catch (e) { claudeFiles = []; }
    for (var i = 0; i < claudeFiles.length; i++) {
      if (!claudeFiles[i].endsWith(".jsonl")) continue;
      var cliSid = claudeFiles[i].slice(0, -".jsonl".length);
      if (workerCliIds.has(cliSid) || knownCliIds.has(cliSid)) continue;
      var desc = readCliSessionDescriptor(cliSid);
      if (!desc && hiddenCliSessions.has(cliSid)) {
        var hiddenSession = hiddenCliSessions.get(cliSid);
        desc = {
          title: hiddenSession.title || "Imported CLI session",
          preview: hiddenSession.title || "",
          createdAt: hiddenSession.createdAt || 0,
          // closedAt is the authoritative close time. Only fall back to
          // lastActivity/createdAt when it exists; never fabricate "now"
          // for legacy sessions closed before closedAt was tracked (that
          // corrupts unrelated sessions with an identical, meaningless
          // "just scanned" timestamp).
          lastActivity: hiddenSession.closedAt || hiddenSession.lastActivity || hiddenSession.createdAt || 0,
        };
      }
      if (!desc) continue;
      var claudeItem = {
        cliSessionId: cliSid,
        title: desc.title,
        preview: desc.preview || "",
        createdAt: desc.createdAt,
        lastActivity: desc.lastActivity,
        tombstoned: tombstones.has(cliSid),
        hidden: hiddenCliIds.has(cliSid),
        coopManaged: coopManagedCliIds.has(cliSid),
        vendor: "claude",
      };
      if (shouldIncludeForImportVendor(claudeItem, vendorFilter)) out.push(claudeItem);
    }

    var codexNames = readCodexThreadNames();
    var codexFiles = listCodexRolloutFiles();
    for (var ci = 0; ci < codexFiles.length; ci++) {
      var cdesc = readCodexSessionDescriptor(codexFiles[ci]);
      if (!cdesc) continue;
      if (workerCliIds.has(cdesc.cliSid) || knownCliIds.has(cdesc.cliSid)) continue;
      var displayTitle = codexNames.get(cdesc.cliSid) || cdesc.title;
      var codexIsHidden = hiddenCliIds.has(cdesc.cliSid);
      // For a session Clay has already closed, the file's own mtime is a
      // scan/write artifact, not the real close time — prefer the
      // authoritative closedAt recorded when Clay hid it.
      var codexHiddenSession = codexIsHidden ? hiddenCliSessions.get(cdesc.cliSid) : null;
      var codexItem = {
        cliSessionId: cdesc.cliSid,
        title: displayTitle,
        preview: cdesc.preview || "",
        createdAt: cdesc.createdAt,
        lastActivity: (codexHiddenSession && codexHiddenSession.closedAt) || cdesc.lastActivity,
        tombstoned: tombstones.has(cdesc.cliSid),
        hidden: codexIsHidden,
        coopManaged: coopManagedCliIds.has(cdesc.cliSid),
        vendor: "codex",
        archived: !!cdesc.archived,
      };
      if (shouldIncludeForImportVendor(codexItem, vendorFilter)) out.push(codexItem);
    }

    var copilotDescs = copilotSessions.listCopilotSessionDescriptors(config.REAL_HOME, cwd);
    for (var gi = 0; gi < copilotDescs.length; gi++) {
      var gdesc = copilotDescs[gi];
      if (!gdesc || workerCliIds.has(gdesc.cliSid) || knownCliIds.has(gdesc.cliSid)) continue;
      var copilotIsHidden = hiddenCliIds.has(gdesc.cliSid);
      var copilotHiddenSession = copilotIsHidden ? hiddenCliSessions.get(gdesc.cliSid) : null;
      var copilotItem = {
        cliSessionId: gdesc.cliSid,
        title: gdesc.title,
        preview: gdesc.preview || "",
        createdAt: gdesc.createdAt,
        lastActivity: (copilotHiddenSession && copilotHiddenSession.closedAt) || gdesc.lastActivity,
        tombstoned: tombstones.has(gdesc.cliSid),
        hidden: copilotIsHidden,
        coopManaged: coopManagedCliIds.has(gdesc.cliSid),
        vendor: "github-copilot",
        copilotFamily: gdesc.copilotFamily || null,
        model: gdesc.model || null,
        providerRouteId: gdesc.providerRouteId || null,
      };
      if (shouldIncludeForImportVendor(copilotItem, vendorFilter)) out.push(copilotItem);
    }

    var listedCliIds = new Set();
    for (var oi = 0; oi < out.length; oi++) {
      if (out[oi] && out[oi].cliSessionId) listedCliIds.add(out[oi].cliSessionId);
    }
    hiddenCliSessions.forEach(function (hs, cliSid) {
      if (!cliSid || workerCliIds.has(cliSid) || listedCliIds.has(cliSid)) return;
      if (hs.compactedIntoLocalId) return;
      var hVendor = hs.vendor || "claude";
      var hFamily = null;
      if (hVendor === "github-copilot") {
        hFamily = hs.copilotFamily || copilotSessions.modelFamily(hs.copilotModel || hs.model) || null;
      }
      var hiddenItem = {
        cliSessionId: cliSid,
        title: hs.title || "Closed session",
        preview: hs.title || "",
        createdAt: hs.createdAt || 0,
        lastActivity: hs.closedAt || hs.lastActivity || hs.createdAt || 0,
        tombstoned: tombstones.has(cliSid),
        hidden: true,
        coopManaged: coopManagedCliIds.has(cliSid),
        vendor: hVendor,
        copilotFamily: hFamily,
        model: hs.model || null,
      };
      if (shouldIncludeForImportVendor(hiddenItem, vendorFilter)) out.push(hiddenItem);
    });

    out.sort(function (a, b) { return (b.lastActivity || 0) - (a.lastActivity || 0); });
    return out;
  }

  function importCliSession(cliSid, vendor, options) {
    if (!cliSid) return null;
    if (!isValidCliSessionId(cliSid)) return null;
    var existing = null;
    sessions.forEach(function (s) {
      if (s.cliSessionId === cliSid) existing = s;
    });
    if (existing) {
      if (existing.hidden) {
        console.warn("[sessions][unhide-watch] un-hiding session localId=" + existing.localId + " cliSid=" + cliSid + " via importCliSession (explicit user import)");
        existing.hidden = false;
        existing.closedAt = null;
        // An explicit import is the owner taking the session back, so release it
        // from Coop control. Un-hiding alone would not stick: while provenance
        // is set the sidebar filters the row out as a terminal Coop projection,
        // and both the completion auto-archive and Coop self-cleanup are free to
        // re-hide it. Releasing makes it a plain owner session, which both paths
        // refuse to touch.
        if (coopProvenance.releaseCoopControl(existing, options && options.ownerId)) {
          console.warn("[sessions][unhide-watch] released session localId=" + existing.localId +
            " cliSid=" + cliSid + " from Coop control on explicit user import");
        }
        restoreCoordinatorWorkers(existing, new Set([existing]));
        tombstones.remove(cliSid);
        saveSessionFile(existing);
        broadcastSessionList();
      }
      return existing.localId;
    }

    var desc = null;
    if (vendor === "codex") {
      var rollout = findCodexRolloutByThreadId(cliSid);
      if (rollout) desc = readCodexSessionDescriptor(rollout);
    } else if (vendor === "github-copilot") {
      desc = copilotSessions.readCopilotSessionDescriptor(config.REAL_HOME, cliSid, cwd);
    } else if (vendor === "claude") {
      desc = readCliSessionDescriptor(cliSid);
    } else {
      desc = readCliSessionDescriptor(cliSid);
      if (!desc) {
        var rollout2 = findCodexRolloutByThreadId(cliSid);
        if (rollout2) desc = readCodexSessionDescriptor(rollout2);
      }
      if (!desc) desc = copilotSessions.readCopilotSessionDescriptor(config.REAL_HOME, cliSid, cwd);
    }
    if (!desc) return null;
    tombstones.remove(cliSid);
    return materializeCliSession(desc);
  }

  return {
    adoptOrphanedCliSessions: adoptOrphanedCliSessions,
    listAdoptableCliSessions: listAdoptableCliSessions,
    importCliSession: importCliSession,
  };
}

module.exports = {
  attachSessionCliImport: attachSessionCliImport,
};
