function attachAutoTitle(ctx) {
  var cwd = ctx.cwd;
  var sm = ctx.sm;
  var getAdapterForSession = ctx.getAdapterForSession;
  var getLinuxUserForSession = ctx.getLinuxUserForSession || function () { return null; };
  var getRuntimeEnv = ctx.getRuntimeEnv || function () { return process.env; };

  function autoGenerateTitle(session) {
    var sessionAdapter = getAdapterForSession(session);
    if (typeof sessionAdapter.generateTitle !== "function") {
      console.log("[auto-title] adapter.generateTitle not available for vendor=" + sessionAdapter.vendor);
      return;
    }
    var userMessages = [];
    for (var i = 0; i < session.history.length; i++) {
      var entry = session.history[i];
      if (entry.type === "user_message" && entry.text) {
        userMessages.push(entry.text.substring(0, 200));
        if (userMessages.length >= 5) break;
      }
    }
    if (userMessages.length === 0) {
      console.log("[auto-title] No user messages found in session " + session.localId);
      return;
    }
    console.log("[auto-title] Calling adapter.generateTitle with " + userMessages.length + " messages for session " + session.localId);

    var titleOpts = { cwd: cwd, dir: cwd, env: getRuntimeEnv(session) };
    var linuxUser = getLinuxUserForSession(session);
    if (linuxUser) titleOpts.linuxUser = linuxUser;
    sessionAdapter.generateTitle(userMessages, titleOpts).then(function(title) {
      if (!title || title.length < 2) return;
      title = title.substring(0, 100);
      if (!session.titleManuallySet) {
        session.title = title;
        session.titleAutoGenerated = true;
        sm.saveSessionFile(session);
        sm.broadcastSessionList();
        if (session.cliSessionId && typeof sessionAdapter.renameSession === "function") {
          sessionAdapter.renameSession(session.cliSessionId, title, titleOpts).catch(function () {});
        }
        console.log("[auto-title] Generated title for session " + session.localId + ": " + title);
      }
    }).catch(function(e) {
      console.error("[auto-title] Failed:", e.message || e);
    });
  }

  return {
    autoGenerateTitle: autoGenerateTitle,
  };
}

module.exports = { attachAutoTitle: attachAutoTitle };
