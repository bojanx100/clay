var TERM_CONTEXT_MAX = 8192;
var TERM_HEAD_SIZE = 2048;
var TERM_TAIL_SIZE = 6144;

function messageHasContent(msg) {
  return !!(msg.text || (msg.images && msg.images.length) || (msg.pastes && msg.pastes.length));
}

function bindSessionMetadata(ctx, ws, msg, session) {
  if (!session.vendor && msg.vendor) {
    session.vendor = msg.vendor;
    ctx.sm.saveSessionFile(session);
    ctx.sm.broadcastSessionList();
  }
  if (!session.ownerId && ws._clayUser && ctx.usersModule.isMultiUser()) {
    session.ownerId = ws._clayUser.id;
    ctx.sm.saveSessionFile(session);
  }
}

function buildUserHistoryMessage(ctx, ws, msg, metadata) {
  var item = { type: "user_message", text: msg.text || "" };
  if (msg.coopTopicRef) item.coopTopicRef = msg.coopTopicRef;
  // Durable reply threading: which record inside the routed topic this message
  // answers. Written once, on this new event only -- no earlier event is
  // touched, so canonical chronology stays append-only.
  if (msg.coopTopicAnchor) item.coopTopicAnchor = msg.coopTopicAnchor;
  if (msg.coopProjectRef) item.coopProjectRef = msg.coopProjectRef;
  if (metadata.intent === "task") {
    item.coordinationRequest = true;
    item.messageIntent = "task";
  } else if (metadata.intent === "queue") {
    item.messageIntent = "queue";
  }
  if (metadata.clientMessageId) item.clientMessageId = metadata.clientMessageId;
  ctx.coopIngress.applyHistoryMetadata(item, metadata);
  if (metadata.wasProcessing && metadata.steer) {
    item.steerDuringProcessing = true;
    item.queueId = metadata.queueId;
    item.queuedPending = true;
  } else if (metadata.shouldQueue) {
    item.queuedDuringProcessing = true;
    item.queueId = metadata.queueId;
    item.queuedPending = true;
  }
  if (ws._clayUser) {
    item.from = ws._clayUser.id;
    item.fromName = ws._clayUser.displayName || ws._clayUser.username || "";
  }
  return item;
}

function saveUploadedImages(ctx, session, msg, historyItem) {
  var savedImagePaths = [];
  if (!msg.images || msg.images.length === 0) return savedImagePaths;
  historyItem.imageCount = msg.images.length;
  var imageRefs = [];
  for (var i = 0; i < msg.images.length; i++) {
    var image = msg.images[i];
    var savedName = ctx.saveImageFile(image.mediaType, image.data, ctx.getLinuxUserForSession(session));
    if (savedName) {
      imageRefs.push({ mediaType: image.mediaType, file: savedName });
      savedImagePaths.push(path.join(ctx.imagesDir, savedName));
      image.savedPath = path.join(ctx.imagesDir, savedName);
    }
  }
  if (imageRefs.length > 0) historyItem.imageRefs = imageRefs;
  return savedImagePaths;
}

function echoUserMessage(ctx, ws, session, historyItem) {
  if (historyItem.queuedDuringProcessing) return;
  var message = ctx.hydrateImageRefs(historyItem);
  if (historyItem.steerDuringProcessing) {
    ctx.sendToSessionOthers(ws, session.localId, message);
  } else {
    ctx.sendToSession(session.localId, message);
  }
}

function ensureSessionTitle(ctx, session, msg) {
  if (session.title) return;
  var titleSource = msg.text || "";
  if (msg.pastes && msg.pastes.length > 0) {
    titleSource += (titleSource ? "\n\n" : "") + msg.pastes.join("\n\n");
  }
  session.title = meaningfulTextTitle(titleSource, 50) || (msg.text || "Image").substring(0, 50);
  session.titleAutoGenerated = true;
  ctx.sm.saveSessionFile(session);
  ctx.sm.broadcastSessionList();
  if (session.cliSessionId && ctx.adapter && typeof ctx.adapter.renameSession === "function") {
    ctx.adapter.renameSession(session.cliSessionId, session.title, { dir: ctx.cwd }).catch(function (e) {
      console.error("[project] SDK renameSession failed:", e.message);
    });
  }
}

function recordUserMessage(ctx, ws, msg, session, metadata) {
  bindSessionMetadata(ctx, ws, msg, session);
  var historyItem = buildUserHistoryMessage(ctx, ws, msg, metadata);
  var savedImagePaths = saveUploadedImages(ctx, session, msg, historyItem);
  if (msg.pastes && msg.pastes.length > 0) historyItem.pastes = msg.pastes;
  if (!historyItem._ts) historyItem._ts = Date.now();
  session.history.push(historyItem);
  coopTopicIngress.bindMessage(ctx, session, msg, session.history.length - 1);
  ctx.sm.appendToSessionFile(session, historyItem);
  echoUserMessage(ctx, ws, session, historyItem);
  ensureSessionTitle(ctx, session, msg);
  return savedImagePaths;
}

function appendPastes(fullText, pastes) {
  for (var i = 0; i < pastes.length; i++) {
    if (fullText) fullText += "\n\n";
    fullText += pastes[i];
  }
  return fullText;
}

function appendImagePaths(fullText, paths, vendor) {
  if (paths.length === 0) return fullText;
  var imagePathLines = paths.map(function (imagePath) {
    return "[Uploaded image: " + imagePath + "]";
  }).join("\n");
  if (vendor === "github-copilot") {
    imagePathLines = "[Note: the user attached image(s), saved at the path(s) below. View each file with your file viewing tool to see its content — it supports image files. Do not claim you cannot see images and do not claim they were lost.]\n" + imagePathLines;
  }
  return imagePathLines + (fullText ? "\n" + fullText : "");
}

function applyHandoffContext(ctx, session, msg, fullText) {
  ctx.recoverHandoffContextForSend(session);
  if (!session.handoffContext) return fullText;
  var handoffImages = handoffPackageModule.loadHandoffImages(session, ctx.imagesDir, 5);
  if (handoffImages.length > 0) msg.images = (msg.images || []).concat(handoffImages);
  fullText = applyHandoffToOutgoingText(session, fullText);
  session.handoffFrom = null;
  ctx.sm.saveSessionFile(session);
  return fullText;
}

function appendMentionContext(session, fullText) {
  if (!session.pendingMentionContexts || session.pendingMentionContexts.length === 0) return fullText;
  var prefix = session.pendingMentionContexts.join("\n\n");
  session.pendingMentionContexts = [];
  return prefix + "\n\n" + fullText;
}

function terminalCursor(session, termId, totalBytes) {
  if (session._termContextCursors && hasOwn.call(session._termContextCursors, termId)) {
    var cursor = session._termContextCursors[termId];
    return cursor > totalBytes ? 0 : cursor;
  }
  return Math.max(0, totalBytes - TERM_CONTEXT_MAX);
}

function terminalDeltaChunks(scrollback, lastCursor) {
  var chunks = [];
  var bytePos = scrollback.bufferStart;
  for (var i = 0; i < scrollback.chunks.length; i++) {
    var chunk = scrollback.chunks[i];
    var chunkEnd = bytePos + chunk.data.length;
    if (chunkEnd > lastCursor) {
      var chunkData = bytePos < lastCursor ? chunk.data.slice(lastCursor - bytePos) : chunk.data;
      chunks.push({ ts: chunk.ts, data: chunkData });
    }
    bytePos = chunkEnd;
  }
  return chunks;
}

function formatTerminalDelta(chunks) {
  var lines = [];
  var lastTimeSec = 0;
  for (var i = 0; i < chunks.length; i++) {
    var chunk = chunks[i];
    var cleaned = chunk.data.replace(/\x1b\[[0-9;]*[a-zA-Z]/g, "");
    if (!cleaned) continue;
    var timeSec = Math.floor(chunk.ts / 1000);
    if (timeSec !== lastTimeSec) {
      lines.push("[" + new Date(chunk.ts).toTimeString().slice(0, 8) + "] " + cleaned);
      lastTimeSec = timeSec;
    } else {
      lines.push(cleaned);
    }
  }
  return lines.join("").trim();
}

function capTerminalDelta(delta, title) {
  if (delta.length <= TERM_CONTEXT_MAX) {
    return { header: "[New terminal output from " + title + "]", delta: delta };
  }
  var head = delta.slice(0, TERM_HEAD_SIZE);
  var tail = delta.slice(-TERM_TAIL_SIZE);
  var omittedBytes = delta.length - TERM_HEAD_SIZE - TERM_TAIL_SIZE;
  var omittedLines = delta.slice(TERM_HEAD_SIZE, delta.length - TERM_TAIL_SIZE).split("\n").length;
  return {
    header: "[New terminal output from " + title + " (large output, head+tail shown)]",
    delta: head + "\n\n... (" + omittedLines + " lines / " + Math.round(omittedBytes / 1024) + "KB omitted) ...\n\n" + tail,
  };
}

function terminalContextPart(ctx, session, termId) {
  var scrollback = ctx.tm.getScrollback(termId);
  if (!scrollback) return "";
  if (!session._termContextCursors) session._termContextCursors = {};
  var lastCursor = terminalCursor(session, termId, scrollback.totalBytesWritten);
  var newBytes = scrollback.totalBytesWritten - lastCursor;
  session._termContextCursors[termId] = scrollback.totalBytesWritten;
  if (newBytes <= 0) return "";
  var delta = formatTerminalDelta(terminalDeltaChunks(scrollback, lastCursor));
  if (!delta) return "";
  var termInfo = ctx.tm.list().find(function (term) { return term.id === termId; });
  var title = termInfo ? termInfo.title : "Terminal " + termId;
  var capped = capTerminalDelta(delta, title);
  return capped.header + "\n```\n" + capped.delta + "\n```";
}

function collectTerminalContext(ctx, session, sourceIds, fullText) {
  var parts = [];
  for (var i = 0; i < sourceIds.length; i++) {
    if (!sourceIds[i].startsWith("term:")) continue;
    var termId = parseInt(sourceIds[i].split(":")[1], 10);
    var part = terminalContextPart(ctx, session, termId);
    if (part) parts.push(part);
  }
  return parts.length > 0 ? parts.join("\n\n") + "\n\n" + fullText : fullText;
}

function parseList(value) {
  try { return typeof value === "string" ? JSON.parse(value) : value; } catch (e) { return null; }
}

function formatConsole(result) {
  if (!result.console || !result.console.logs) return "";
  var logs = parseList(result.console.logs);
  if (!logs || logs.length === 0) return "";
  var lines = [];
  var recent = logs.slice(-50);
  for (var i = 0; i < recent.length; i++) {
    var entry = recent[i];
    var ts = entry.ts ? new Date(entry.ts).toTimeString().slice(0, 8) : "";
    lines.push("[" + ts + " " + (entry.level || "log").toUpperCase() + "] " + (entry.text || ""));
  }
  return "Console:\n" + lines.join("\n");
}

function formatNetwork(result) {
  if (!result.network || !result.network.network) return "";
  var requests = parseList(result.network.network);
  if (!requests || requests.length === 0) return "";
  var lines = [];
  var recent = requests.slice(-30);
  for (var i = 0; i < recent.length; i++) {
    var request = recent[i];
    var line = (request.method || "GET") + " " + (request.url || "") + " " +
      (request.status || 0) + " " + (request.duration || 0) + "ms";
    if (request.error) line += " [" + request.error + "]";
    lines.push(line);
  }
  return "Network (last " + recent.length + " requests):\n" + lines.join("\n");
}

function formatPageText(result) {
  if (!result.pageText || (!result.pageText.text && !result.pageText.value)) return "";
  var text = result.pageText.text || result.pageText.value;
  if (!text) return "";
  return "Page text:\n" + (text.length > 32768 ? text.substring(0, 32768) + "\n... (truncated)" : text);
}

function saveScreenshot(ctx, session, tabInfo, tabLabel, result) {
  if (!result.screenshot || !result.screenshot.image) return null;
  try {
    var data = result.screenshot.image;
    var file = ctx.saveImageFile("image/png", data, ctx.getLinuxUserForSession(session));
    if (!file) return null;
    return {
      mediaType: "image/png", data: data, file: file,
      tabTitle: tabLabel, tabUrl: tabInfo ? tabInfo.url : "",
      tabFavIconUrl: tabInfo ? tabInfo.favIconUrl : "",
      path: path.join(ctx.imagesDir, file),
    };
  } catch (e) {
    return null;
  }
}

function formatBrowserResult(ctx, session, tabInfo, result) {
  if (!result) return { text: "", screenshots: [] };
  var tabLabel = tabInfo ? (tabInfo.title || tabInfo.url || "Tab " + tabInfo.id) : "Tab";
  var parts = [];
  var consoleText = formatConsole(result);
  var networkText = formatNetwork(result);
  var pageText = formatPageText(result);
  if (consoleText) parts.push(consoleText);
  if (networkText) parts.push(networkText);
  if (pageText) parts.push(pageText);
  var screenshot = saveScreenshot(ctx, session, tabInfo, tabLabel, result);
  if (screenshot) parts.push("[Screenshot saved: " + screenshot.path + "]");
  if (result.console && result.console.error) parts.push("(Console error: " + result.console.error + ")");
  if (result.network && result.network.error) parts.push("(Network error: " + result.network.error + ")");
  return {
    text: parts.length > 0 ? "[Browser tab: " + tabLabel + "]\n" + parts.join("\n\n") : "",
    screenshots: screenshot ? [screenshot] : [],
  };
}

function collectBrowserContext(ctx, session, tabSources, tabList) {
  if (tabSources.length === 0) return Promise.resolve({ text: "", screenshots: [] });
  var requests = tabSources.map(function (sourceId) {
    return ctx.requestTabContext(parseInt(sourceId.split(":")[1], 10));
  });
  return Promise.all(requests).then(function (results) {
    var parts = [];
    var screenshots = [];
    for (var i = 0; i < results.length; i++) {
      var tabId = parseInt(tabSources[i].split(":")[1], 10);
      var formatted = formatBrowserResult(ctx, session, tabList[tabId], results[i]);
      if (formatted.text) parts.push(formatted.text);
      screenshots = screenshots.concat(formatted.screenshots);
    }
    return { text: parts.join("\n\n---\n\n"), screenshots: screenshots };
  });
}

function appendScreenshotPreviews(ctx, session, msg, screenshots) {
  if (screenshots.length === 0) return;
  if (!msg.images) msg.images = [];
  for (var i = 0; i < screenshots.length; i++) {
    var screenshot = screenshots[i];
    session.history.push({
      type: "context_preview",
      tab: {
        title: screenshot.tabTitle || "",
        url: screenshot.tabUrl || "",
        favIconUrl: screenshot.tabFavIconUrl || "",
        screenshotFile: screenshot.file,
      },
    });
    ctx.sendToSession(session.localId, {
      type: "context_preview",
      tab: {
        title: screenshot.tabTitle || "",
        url: screenshot.tabUrl || "",
        favIconUrl: screenshot.tabFavIconUrl || "",
        screenshotUrl: "/p/" + ctx.slug + "/images/" + screenshot.file,
      },
    });
    msg.images.push({
      mediaType: screenshot.mediaType,
      data: screenshot.data,
      savedPath: path.join(ctx.imagesDir, screenshot.file),
    });
  }
  ctx.sm.saveSessionFile(session);
}

function emailContextPromise(ctx, ws, session, sourceIds) {
  var emailSources = sourceIds.filter(function (id) { return id.startsWith("email:"); });
  if (emailSources.length === 0 || !ctx.email) return Promise.resolve("");
  var userId = (ws._clayUser && ws._clayUser.id) || "default";
  return ctx.email.getEmailContext(userId, session.localId).catch(function () { return ""; });
}

function dispatchWithContexts(ctx, prepared) {
  if (ctx.coopIngress.dispatch(prepared)) return;
  var tabList = ctx.browserState._browserTabList || {};
  var tabSources = prepared.sourceIds.filter(function (id) {
    if (!id.startsWith("tab:")) return false;
    return !!tabList[parseInt(id.split(":")[1], 10)];
  });
  emailContextPromise(ctx, prepared.ws, prepared.session, prepared.sourceIds).then(function (emailText) {
    var fullText = emailText ? emailText + "\n\n" + prepared.fullText : prepared.fullText;
    collectBrowserContext(ctx, prepared.session, tabSources, tabList).then(function (browser) {
      if (browser.text) fullText = "[The following browser tab data is automatically attached as context sources. Do NOT call browser_read_page, browser_console, browser_network, or browser_screenshot for these tabs -- the data is already here.]\n\n" + browser.text + "\n\n" + fullText;
      appendScreenshotPreviews(ctx, prepared.session, prepared.msg, browser.screenshots);
      ctx.queue.dispatchPreparedToSdk(prepared.session, {
        // Who actually sent this turn. The Done-workflow gate must verify the
        // owner rather than assume the session's owner typed it.
        actorUserId: (prepared.ws && prepared.ws._clayUser && prepared.ws._clayUser.id) || null,
        finalText: fullText,
        images: prepared.msg.images,
        steer: prepared.metadata.steer,
        queueId: prepared.metadata.queueId,
        displayText: prepared.msg.text || "",
        imageCount: prepared.metadata.displayImageCount,
        clientMessageId: prepared.metadata.clientMessageId,
        pastes: prepared.msg.pastes || null,
        fromQueue: false,
        intent: prepared.metadata.intent,
      });
    });
  });
}
function logPasteDelivery(session, metadata, msg, pasteTextLenBefore, fullText) {
  try {
    var pasteCount = (msg.pastes && msg.pastes.length) || 0;
    var pasteChars = 0;
    for (var i = 0; i < pasteCount; i++) pasteChars += (msg.pastes[i] || "").length;
    console.log("[clay-paste] handleUserMessage: session=" + session.localId +
      " steer=" + (msg.steer === true) + " wasProcessing=" + metadata.wasProcessing +
      " pastes=" + pasteCount + " pasteChars=" + pasteChars +
      " fullTextLen " + pasteTextLenBefore + "->" + fullText.length);
  } catch (e) {}
}

function prepareAgentText(ctx, ws, metadata, msg, session, savedImagePaths) {
  var fullText = msg.text || "";
  if (ctx.queue.shouldRetryAfterApiError && ctx.queue.shouldRetryAfterApiError(session, msg.text || "")) {
    fullText = "Retry the previous provider/API failure and continue the interrupted work. Do not treat the API error text as the task; resume the work that was interrupted before that failure.";
  }
  fullText = coopChannels.applyChannelScope(session, fullText);
  fullText = applyHandoffContext(ctx, session, msg, fullText);
  var vendorCannotSeeImages = session.vendor === "github-copilot";
  if (vendorCannotSeeImages && savedImagePaths.length > 0 && !session._copilotImagePathToastShown) {
    session._copilotImagePathToastShown = true;
    ctx.sendTo(ws, {
      type: "toast", level: "info", message: "Images shared as files",
      detail: "GitHub Copilot receives pasted images as saved files and views them with its file tool.",
    });
  }
  fullText = appendImagePaths(fullText, savedImagePaths, vendorCannotSeeImages ? session.vendor : null);
  var pasteTextLenBefore = fullText.length;
  if (msg.pastes && msg.pastes.length > 0) fullText = appendPastes(fullText, msg.pastes);
  logPasteDelivery(session, metadata, msg, pasteTextLenBefore, fullText);
  fullText = appendMentionContext(session, fullText);
  return ctx.coopIngress.applyText(metadata, msg, fullText);
}

function handleMessage(ctx, ws, msg) {
  if (!msg || msg.type !== "message") return false;
  if (!messageHasContent(msg)) return true;
  var session = ctx.getSessionForMessage(ws, msg);
  if (!session) return true;
  if (ctx.canCaptureCoopHandoff(session, ws, msg.text)) {
    var captured = ctx.coopHandoffTraceStore.recordIntent({
      id: msg.handoffTraceId,
      ownerId: ctx.handoffTraceOwnerId(ws),
      channel: msg.channel,
      expectedTarget: msg.handoffTarget,
      requiresAssistantObservation: true,
      observeAssistantTurns: ctx.observeAssistantTurns(session),
    });
    if (captured && captured.ok) ctx.sendTo(ws, { type: "coop_handoff_intent", handoffTraceId: captured.id });
  }
  if (ctx.hasStaleProcessingState(session)) {
    console.warn("[project] Clearing stale processing state after completed turn for session " + session.localId);
    session.isProcessing = false;
    ctx.onProcessingChanged();
    ctx.sm.broadcastSessionList();
  }
  if (ctx.handleSwitchCommand && typeof msg.text === "string" && /^\/(switch|provider)(\s|$)/i.test(msg.text.trim())) {
    ctx.handleSwitchCommand(ws, session, msg.text.trim());
    return true;
  }
  if (!coopTopicIngress.prepareIngress(ctx, ws, msg, session)) return true;
  var coopIngress = ctx.coopControl ? ctx.coopControl.reserveIngress(session, msg) : null;
  if (coopIngress && coopIngress.coop && !coopIngress.accepted) {
    ctx.coopControl.publish(session);
    return true;
  }
  if (coopIngress && coopIngress.coop && ctx.coopIngress.unavailableProjectRef(msg.coopProjectRef, ws)) {
    ctx.coopControl.recordAttention(session, "project_target_unavailable");
    ctx.sendTo(ws, { type: "error", text: "The selected project target is unavailable. Coop did not fall back to Lead-local execution." });
    return true;
  }
  // Every target check above passed, so the unavailable target that recorded
  // durable attention is resolved and must stop holding Coop at Waiting. This
  // is deliberately the single accept point, not the earlier route check:
  // clearing sooner would flash Idle before a later check re-recorded attention.
  if (coopIngress && coopIngress.coop && ctx.coopControl &&
      typeof ctx.coopControl.clearAttention === "function") {
    ctx.coopControl.clearAttention(session);
  }
  var metadata = ctx.coopIngress.buildMetadata(session, msg, coopIngress);
  var savedImagePaths = recordUserMessage(ctx, ws, msg, session, metadata);
  var sourceIds = ctx.loadContextSources(ctx.slug, session.localId);
  var fullText = prepareAgentText(ctx, ws, metadata, msg, session, savedImagePaths);
  ctx.coopIngress.recordPrepared(session, metadata, msg, fullText);
  dispatchWithContexts(ctx, {
    ws: ws, session: session, msg: msg, metadata: metadata,
    sourceIds: sourceIds,
    fullText: metadata.coopIngress ? fullText : collectTerminalContext(ctx, session, sourceIds, fullText),
  });
  return true;
}

function attachProjectUserMessageContext(ctx) {
  ctx.coopIngress = coopForegroundIngress.attachCoopForegroundIngress(ctx);
  return {
    handleUserMessage: function (ws, msg) { return handleMessage(ctx, ws, msg); },
  };
}

